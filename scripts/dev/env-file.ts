/**
 * The git-ignored `.env.dev` file: dev-only secrets created on the first `npm run dev`, reused after.
 *
 * WHY A SEPARATE FILE: the root `.env` belongs to the docker rehearsal / production deploy and is
 * NEVER read or modified by the dev tooling. `.env.dev` holds random local-only values, so a fresh
 * clone needs zero manual setup and no real secret ever lands on a laptop by accident.
 * `.env.*` is ignored by .gitignore (except .env.example) and by .dockerignore.
 */
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';

/** Generated once with 32 random bytes (64 hex chars — never needs URL escaping). */
export const GENERATED_KEYS = [
  'API_KEY_PEPPER',
  'USER_KEY_SECRET',
  'IP_HASH_SECRET',
  'LIBAS_JWT_SECRET',
  'NEXUS_APP_DB_PASSWORD',
  'DEV_DB_PASSWORD',
] as const;
export type GeneratedKey = (typeof GENERATED_KEYS)[number];

/** Written by "Seed demo data" on the launcher page; removed by `npm run dev:reset`. */
export const DEMO_KEYS = ['DEMO_SECRET_KEY', 'DEMO_PUBLISHABLE_KEY'] as const;
export type DemoKey = (typeof DEMO_KEYS)[number];

export type DevEnvValues = Readonly<Record<GeneratedKey, string>> &
  Readonly<Partial<Record<DemoKey, string>>>;

export interface EnsureResult {
  values: DevEnvValues;
  /** True when the file did not exist and was just created. */
  created: boolean;
  /** Generated keys that were missing from an existing file and have been added. */
  addedKeys: GeneratedKey[];
}

const HEADER = [
  '# Data Nexus Traffic — LOCAL DEV ONLY settings, generated by `npm run dev` (scripts/dev/env-file.ts).',
  '# Git-ignored. Random values for this laptop only: NEVER copy them to a server or into .env.',
  '# Start fresh: npm run dev:reset (drops the dev database) and delete this file.',
];

const LINE_PATTERN = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/;

/** Default secret generator: 32 random bytes as hex. */
export function randomHex(): string {
  return randomBytes(32).toString('hex');
}

function unquote(value: string): string {
  const quoted = /^(['"])(.*)\1$/.exec(value);
  return quoted ? (quoted[2] ?? '') : value;
}

/** KEY=VALUE lines → map. Comments and blank lines are ignored; surrounding quotes are removed. */
export function parseEnvText(text: string): Map<string, string> {
  const values = new Map<string, string>();
  for (const line of text.split(/\r?\n/)) {
    if (line.trim().startsWith('#')) continue;
    const match = LINE_PATTERN.exec(line);
    if (match?.[1]) values.set(match[1], unquote(match[2] ?? ''));
  }
  return values;
}

/**
 * Applies `changes` to env text: a string sets (replacing the existing line in place or appending),
 * null deletes. Comments, order and unrelated keys are kept.
 */
export function applyEnvChanges(text: string, changes: Readonly<Record<string, string | null>>): string {
  const pending = new Map(Object.entries(changes));
  const lines = text === '' ? [] : text.replace(/\r?\n$/, '').split(/\r?\n/);
  const out: string[] = [];
  for (const line of lines) {
    const key = line.trim().startsWith('#') ? undefined : LINE_PATTERN.exec(line)?.[1];
    if (key === undefined || !pending.has(key)) {
      out.push(line);
      continue;
    }
    const value = pending.get(key);
    pending.delete(key);
    if (value !== null && value !== undefined) out.push(`${key}=${value}`);
  }
  for (const [key, value] of pending) {
    if (value !== null) out.push(`${key}=${value}`);
  }
  return `${out.join('\n')}\n`;
}

function readText(file: string): string | null {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw err;
  }
}

function writeText(file: string, text: string): void {
  // 0o600: owner-only on POSIX (ignored on Windows, where the user profile ACL applies).
  fs.writeFileSync(file, text, { encoding: 'utf8', mode: 0o600 });
}

function toValues(map: Map<string, string>): DevEnvValues {
  const values: Record<string, string> = {};
  for (const key of [...GENERATED_KEYS, ...DEMO_KEYS]) {
    const value = map.get(key);
    if (value) values[key] = value;
  }
  return values as unknown as DevEnvValues;
}

/** Reads the file (null when it does not exist). */
export function readDevEnvFile(file: string): DevEnvValues | null {
  const text = readText(file);
  return text === null ? null : toValues(parseEnvText(text));
}

/**
 * Creates the file with fresh secrets on the first run; on later runs reuses it and only fills in
 * generated keys that are missing (an older file, or a key deleted by hand).
 */
export function ensureDevEnvFile(file: string, generate: () => string = randomHex): EnsureResult {
  const existing = readText(file);
  const current = existing === null ? new Map<string, string>() : parseEnvText(existing);
  const addedKeys = GENERATED_KEYS.filter((key) => !current.get(key));
  if (existing !== null && addedKeys.length === 0) {
    return { values: toValues(current), created: false, addedKeys: [] };
  }
  const changes = Object.fromEntries(addedKeys.map((key) => [key, generate()]));
  const base = existing ?? `${HEADER.join('\n')}\n`;
  const next = applyEnvChanges(base, changes);
  writeText(file, next);
  return {
    values: toValues(parseEnvText(next)),
    created: existing === null,
    addedKeys: existing === null ? [] : addedKeys,
  };
}

/** Sets (string) or removes (null) keys in an existing file, keeping everything else. */
export function updateDevEnvFile(file: string, changes: Readonly<Record<string, string | null>>): void {
  const text = readText(file) ?? `${HEADER.join('\n')}\n`;
  writeText(file, applyEnvChanges(text, changes));
}
